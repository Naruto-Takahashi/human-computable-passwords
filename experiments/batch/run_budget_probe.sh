#!/usr/bin/env bash
# =============================================================================
# 実験8a: 学習予算を外して「離陸するか」を確かめる（探り）
#
# 【なぜこれを回すのか】
# 実験7（2026-09-13）で，実験5b・6 の「学習できるかどうかは鍵で決まる」という
# 結論が崩れた。鍵6 は data_seed を変えると 10.2% / 100.0% / 96.2% となり，
# 10.2% は外れくじだった。離陸エポックは1〜5にばらつき，鍵6/ds=0 だけが
# 5エポック以内に間に合わなかっただけである。
#
# つまりこれまで測っていたのは関数の難しさではなく
#     「5エポックという予算の中で離陸が起きたか」
# だった（docs/measurement_audit.md）。予算を外さないと何も測れない。
#
# 【設計上の判断が2つある】
#
# (1) 学習率を**定数**にする（--lr_scheduler constant）
#     既定の linear は全ステップにわたって0まで減衰するため，エポック数を
#     変えると学習率の下がり方まで変わる。20エポック版は40エポック版の前半とは
#     別の軌道になり，「離陸に要したステップ数」が**予算の宣言に依存してしまう**。
#     定数にすれば，短い run は長い run の前半と一致し，離陸ステップ数が
#     課題の性質として意味を持つ。実験8b で難易度をこの量で測るための前提でもある。
#
#     代償: 終盤の焼きなましが無いので最終損失はやや粗くなる。ただし本実験で
#     見たいのは離陸の有無とその時期であり，最後の詰めではない。
#
#     注意: 過去の実測（静的参照の離陸は1〜5エポック）はすべて linear での値なので，
#     定数LRの値と直接は比べられない。そのため下の (B) を同じ条件で回し，
#     **この実験の中に静的参照の基準線を作る**。
#
# (2) 本命を**2シード**回す
#     実験7 の結論は「1条件1runでは解釈できない」だった。その直後に1runで
#     「動的参照は離陸しない」と結論するのでは同じ誤りを繰り返す。
#     設定を完全に固定しても GPU の非決定性だけで離陸が1エポックぶれることが
#     分かっているため，最低2本は要る。
#
# 【条件】20エポック = 2500ステップ ≒ 6.5時間/本，計3本で約20時間
#
#   (B)  table_add3_k10  鍵6 ds0 シード42  … 静的参照の基準線。
#        5エポックで唯一離陸しなかった条件（10.2%・検証損失 0.1906 で不動）。
#        同じ鍵の別データでは 100.0% と 96.2% になるので，本来は学習できる。
#        これが離陸すれば「予算が測定器だった」という診断の裏づけになり，
#        同時に定数LRでの静的参照の離陸ステップ数が得られる。
#
#   (A1) func_22_k10  鍵0 ds0 シード42   … 動的参照1本。本命。
#   (A2) func_22_k10  鍵0 ds0 シード1    … 同条件の2本目。
#        鍵0 は静的参照が 99.6% で学習できる鍵（実験6）。その上で5エポックでは
#        20.0%・検証損失 0.1797 のまま動かなかった。
#
# 【見どころ】
#   (B) が離陸する        → 予算不足だったという診断が実証される
#   (A1)(A2) とも離陸する → 動的参照は「学習できない」のではなく「遅い」。
#                          離陸ステップ数という連続量で難易度を測れる（実験8bへ）
#   (A1)(A2) とも離陸せず → 静的の4倍以上の予算でも学習できない。2本の独立な
#                          run が支持するので，1runでの主張より強い
#   片方だけ離陸する      → ばらつきが極めて大きい。シードを増やす必要がある
#
# 【測り方】
# 主データは正解率ではなく**検証損失の軌跡**である。正解率は10%が偶然と
# 区別できないが，検証損失は下がり始めた瞬間から動く。走行中でも読める：
#     .venv/bin/python -c "import pandas as pd,sys; d=pd.read_csv(sys.argv[1]); \
#       print(d[['epoch','loss','eval_loss']].dropna().to_string())" <run_dir>/history.csv
#
# 【20エポックの根拠】
# 静的参照の離陸は実測10本で 1〜5エポック（最大5）。20はその4倍にあたる。
# ここで離陸しなければ「静的の4倍以上」と言える。定数LRなので，足りなければ
# 同じ設定で延長でき，前半をやり直す必要はない。
# =============================================================================
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/_common.sh"

HCP_TOTAL=3
hcp_init "実験8a: 学習予算の探り"
HCP_EPOCHS=20
HCP_LR_SCHEDULER=constant

# 基準線を先に取る（実験3の教訓：基準線が無いと本命を解釈できない）
hcp_run --algorithm table_add3_k10 --key_seed 6 --data_seed 0 --seed 42
hcp_run --algorithm func_22_k10    --key_seed 0 --data_seed 0 --seed 42
hcp_run --algorithm func_22_k10    --key_seed 0 --data_seed 0 --seed 1

hcp_finish
