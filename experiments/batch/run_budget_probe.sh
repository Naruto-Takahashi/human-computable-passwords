#!/usr/bin/env bash
# =============================================================================
# 実験8a: 学習予算を外して「離陸するか」を確かめる（探り）
#
# 【なぜこれを回すのか】
# 実験7（2026-09-13）で，実験5b・6 の「学習できるかどうかは鍵で決まる」という
# 結論が崩れた。鍵6 は data_seed を変えると 10.2% / 100.0% / 96.2% となり，
# 10.2% は外れくじだった。離陸エポックは1〜4にばらつき，鍵6/ds=0 だけが
# 5エポック以内に間に合わなかっただけである。
#
# つまりこれまで測っていたのは関数の難しさではなく
#     「5エポックという予算の中で離陸が起きたか」
# だった（docs/training_dynamics.md）。予算を外さないと何も測れない。
#
# 【この探りで決めること】
# 本命の問い「動的参照は学習できないのか，遅いだけなのか」に答えるには，
# まず離陸に何エポック要るのかの見当が要る。5エポックの8倍（40エポック，
# 5000ステップ）を与えて，次の2本を観察する。
#
#   (A) func_22_k10  鍵0  … 動的参照1本。研究の主張が乗っている本命。
#       鍵0 は静的参照が 99.6% で学習できる鍵であり（実験6），その上で
#       5エポックでは 20.0%・検証損失 0.1797 のまま動かなかった。
#
#   (B) table_add3_k10 鍵6 データ0 … 静的参照。5エポックで唯一離陸しなかった条件
#       （10.2%・検証損失 0.1906 で不動）。同じ鍵・別データでは 100.0% と 96.2% に
#       なるので，これは「遅れて離陸するはず」の対照になる。予算を伸ばして
#       離陸すれば，「予算が測定器だった」という診断そのものの裏づけになる。
#
# 【見どころ】
#   (B) が離陸する  → 予算不足だったという診断が実証される
#   (A) が離陸する  → 動的参照は「学習できない」のではなく「遅い」。難易度を
#                     離陸ステップ数という連続量で測り直せる（実験8b へ）
#   (A) が離陸しない → 8倍の予算でも学習できない。経路Bの主張が予算の議論に
#                     耐える形で確定する
# どちらに転んでも実験8b の設計が決まる。
#
# 【測り方】
# 正解率ではなく**検証損失の軌跡**が主データである。正解率は10%が偶然と
# 区別できないが，検証損失は下がり始めた瞬間から動く。エポックごとに
# history.csv に記録されるので，走行中でも進捗が読める：
#     .venv/bin/python -c "import pandas as pd,sys; d=pd.read_csv(sys.argv[1]); \
#       print(d[['epoch','loss','eval_loss']].dropna().to_string())" <run_dir>/history.csv
#
# 【注意：40エポックは5エポック版の続きではない】
# 学習率は全ステップにわたって線形に0まで減衰する。40エポック指定では
# 5エポック目時点の学習率が 1.8e-4 と高いままで，5エポック版とは別の軌道を通る。
# 「より多くの最適化を与える」という仮説の検証としては正しいが，
# 「5エポック版を延長した」とは言えない。報告時に書き分けること。
#
# 【所要】
# 1本あたり 5000ステップ ≒ 13時間（実測 9.1 秒/ステップ）。2本で約26時間。
# =============================================================================
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/_common.sh"

HCP_TOTAL=2
hcp_init "実験8a: 学習予算の探り"
HCP_EPOCHS=40

# 本命を先に回す。13時間後に(A)の結論が出る。
hcp_run --algorithm func_22_k10    --key_seed 0 --data_seed 0
hcp_run --algorithm table_add3_k10 --key_seed 6 --data_seed 0

hcp_finish
