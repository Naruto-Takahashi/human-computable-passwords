#!/usr/bin/env bash
# =============================================================================
# 実験10: 場合の数を揃えて，静的と動的の崩壊点を比べる
#
# 【なぜ】実験9 で「動的参照を含む関数は学習できない」は反証された
#   （鍵4マスで未出399件すべて正解）。しかしこれが否定したのは
#   **絶対的な不可能性**だけである。次の2つは未解決のまま残っている。
#
#     (b) 動的参照は難しさを大きく増すのか
#     (c) 実用的な鍵サイズでは動的参照が壁になるのか
#
#   (c) こそ安全性にとって意味のある主張だが，鍵10マスの m=2 は 9.2% のままで，
#   その失敗が「規模のせい」か「動的参照のせい」か切り分けられていない。
#
# 【なぜ規模では説明できないか】「真の場合の数」（どの鍵でも同じ答えを与える
#   入力を同一視した数）を測ると，規模は単調に効いていない。
#
#     narrowptr_k4_m1      20 通り  100.0%
#     table_add6_k4        84 通り   10.6%  ← 小さいのに失敗
#     table_add3_k10      220 通り   99.6%
#     narrowptr_k4_m2     740 通り  100.0%  ← 大きいのに成功
#     narrowptr_k10_m2 43,831 通り    9.2%
#
# 【設計】加算の項数を3に揃えたまま，場合の数を横軸にして崩壊点を比べる。
#   table_add3 は3項・位置3（静的），narrowptr_m2 は3項・位置6（動的）で，
#   項数が揃っているため違いは間接参照の有無に絞られる。
#
#     場合の数   静的                    動的
#     約 700     table_add3_k15 (680)    narrowptr_k4_m2 (740)  ← 測定済み 100%
#     約 3,000   table_add3_k26 (3,276)  narrowptr_k5_m2 (3,035)
#
# 【読み方】
#   両方とも約3,000で成功  → 動的参照はこの規模まで寄与しない。
#                            鍵10マスの失敗（43,831）は規模の効果
#   動的だけ約3,000で失敗  → **動的参照は難しさに寄与する**。(b) が復活し，
#                            弱い形で元の主張が戻る
#   両方とも約3,000で失敗  → 効いているのは規模。崩壊点は 740 と 3,000 の間
#
# 【table_add3_k26 を含める理由】既存だが 5エポック・線形減衰でしか測っておらず
#   12〜14%（床）だった。20エポック・定数で離陸すれば，**偽陰性の2例目**になる
#   （1例目は実験8a の table_add3_k10 鍵6，10.2% → 100.0%）。
#   どちらに転んでも価値がある。
#
# 【見直し（CLAUDE.md のチェックリスト）】
#   評価件数       500件
#   基準線         各条件の衝突確率。鍵サイズが違うので条件ごとに異なる
#   基準線を先に   静的（table_add3_k15）を先に回す。ここが落ちたら比較が成立しない
#   床の可能性     どの組合せでも解釈が用意してある（上記「読み方」）
#   鍵の本数       鍵0 のみ。まず崩壊点の有無を見る。境界が出たら鍵を足す
#   1条件1回       本実験も1runずつ。境界が出た条件だけ別シードを足す
#   予算の混入     実験8a・8b・9 と同じ 20エポック・定数学習率
#   過去との比較   narrowptr_k4_m2（実験9，同一予算・同一評価件数）をそのまま使う
#   既出／未出     鍵が小さい条件があるので必ず分けて集計する
#                  （make seen-unseen RUN=<評価の run>）
#
# 【この設計の弱点】「真の場合の数」は尺度として不完全である。どの場合に当たるかを
#   判別する手間を反映しないため（84通りでも判別には6個を足す必要がある）。
#   したがって本実験は「場合の数を揃えた」のではなく「場合の数という一つの軸で
#   揃えた」にすぎない。結果の解釈はこの限界のもとで行う。
#
# 所要: 1本 約7.5時間 × 3本 ≒ 22.5時間
# =============================================================================
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/_common.sh"

HCP_TOTAL=3
hcp_init "実験10: 場合の数ラダー（静的 対 動的）"
HCP_EPOCHS=20
HCP_LR_SCHEDULER=constant

hcp_run --algorithm table_add3_k15  --key_seed 0 --data_seed 0 --seed 42
hcp_run --algorithm table_add3_k26  --key_seed 0 --data_seed 0 --seed 42
hcp_run --algorithm narrowptr_k5_m2 --key_seed 0 --data_seed 0 --seed 42

hcp_finish
