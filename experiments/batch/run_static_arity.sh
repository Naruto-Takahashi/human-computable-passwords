#!/usr/bin/env bash
# =============================================================================
# 実験9 段階2: 位置数を揃えて動的参照だけを変える（4つ目の交絡の切り分け）
#
# 【なぜ】経路Bのこれまでの結果は，**答えを決める位置の数**と**動的参照の有無**が
#   完全に相関しており，どちらが壁なのか区別できない（plan.md §3.1.4）。
#
#     narrowptr_k10_m1  位置3  98.6%（未出でも 96.2%）
#     narrowptr_k10_m2  位置6   9.2%
#
#   m を1から2に上げると動的参照が生まれるが，同時に関数の引数が3個から6個に
#   倍増している。lookup（位置1）・table_add（位置2）・table_add3（位置3）が
#   学習でき，位置6以上が全滅という並びは「位置数だけ」でも説明できてしまう。
#
#   そこで動的参照を持たないまま位置数だけ6にする。
#
#     table_add6_k4:  Z = (X0 + X1 + X2 + X3 + X4 + X5) mod 10
#
# 【対照は段階1 の中にある】段階1 で回した narrowptr_k4_m2 と，
#   位置数・組み合わせ数・被覆率が一致する。違いはポインタの有無だけ。
#
#     条件                動的参照  位置数  組合せ  被覆    衝突確率
#     narrowptr_k4_m2     あり       6     4,096  21.7%   10.8%
#     table_add6_k4       なし       6     4,096  21.7%   10.0%
#
# 【解釈は対称ではない】
#   成功 → 決定的。位置6でも静的なら学習できる＝壁は動的参照（H1 確定）
#   失敗 → 曖昧。位置数のせいか「6個足す」算術の重さのせいか分からない
#          （m=2 は位置を6個読むが足すのは3個）。
#          そのときは table_add5_k4 → table_add4_k4 と刻んで静的の天井を特定する
#          （用意済み。被覆は n=5 で 62.4%，n=4 で 98.0%）
#
# 【見直し（CLAUDE.md のチェックリスト）】
#   評価件数       500件
#   基準線         衝突確率 10.0%（鍵35）。最頻値 10.6%
#   基準線を先に   対照（narrowptr_k4_m2）は段階1 で先に回している
#   床の可能性     失敗しても静的ラダーで天井を特定できる設計にしてある
#   鍵の本数       鍵35 のみ。段階1 と揃えるため
#   1条件1回       段階1 と同じ制約。境界が決まったら別シードを足す
#   予算の混入     実験8a・8b・9段階1 と同じ 20エポック・定数学習率
#   過去との比較   段階1（同じ鍵・同じ予算・同じ評価件数）とだけ比べる
#
# 【この設計の弱点】被覆 21.7% なので評価500件の約2割が学習で既出になる。
#   評価後に tools/seen_unseen.py で既出／未出に分けること
#   （make seen-unseen RUN=<評価の run>）。未出の正解率が主データ。
#
# 【どう転んでも報告できるか】
#   成功 → 壁は動的参照。経路Bの中心的主張が初めて交絡なしで裏づけられる
#   失敗 → H1 は保留。静的ラダーへ進み，壁を「引数の多さ」として測り直す
#
# 所要: 約7.5時間
# =============================================================================
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/_common.sh"

HCP_TOTAL=1
hcp_init "実験9 段階2: 静的で位置6（交絡の切り分け）"
HCP_EPOCHS=20
HCP_LR_SCHEDULER=constant

hcp_run --algorithm table_add6_k4 --key_seed 35 --data_seed 0 --seed 42

hcp_finish
