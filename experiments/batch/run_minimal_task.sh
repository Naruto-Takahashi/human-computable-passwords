#!/usr/bin/env bash
# =============================================================================
# 実験9 段階1: 最小課題（鍵4マス）で容量による説明を排除する
#
# 【なぜ】実験8b 段階1 で壁が m=1（98.6%）と m=2（9.2%）の間にあると分かったが，
#   「3B という小さいモデルを使ったための性能不足では」という反論が残った。
#   7B への切り替えは 8GB の GPU に載らず断念したため（log.md 2026-09-19），
#   モデルを大きくする代わりに**課題を小さくして**反論を潰す。
#
#   鍵を 10 マス → 4 マスに縮めると，答えを決める組み合わせが
#   1,000,000 通り → 4,096 通り（1/244）になる。
#   ここまで記憶の負担を落としても動的参照が学習されないなら，
#   「容量が足りなかった」では説明できない。
#
#   narrowptr_k4_m{m}:  j = (X[10] + X[11]) mod m,  Z = (X[j] + X[12] + X[13]) mod 10
#
# 【鍵を seed 35 に固定する理由】k=4 では鍵の選別が要る。実測（鍵100本）で
#   - 4マスの偶奇が揃うと j が 0 に固定され，動的参照が消える（100本中12本）
#   - 値に重複があると答えが偏り，衝突確率が 10.5% → 16.7% に上がる
#   seed 35 の鍵 [1,3,8,4] は4値すべて相異なり偶奇も混ざるため，
#   衝突確率 10.8% / 最頻値 14.0% と，実験8b（鍵0，10.5% / 13.0%）に揃う。
#   **基準線が揃うので 8b の m=1 98.6% / m=2 9.2% とそのまま並べられる。**
#
# 【縮小の停止条件】k=4 が下限である（k=3 以下は衝突確率 16.2% 以上に歪み，
#   8b と比較できない）。k=4 で失敗してもこれ以上は縮めない。
#   根拠と作法は plan.md §3.1.3 に先に明記した。
#
# 【見直し（CLAUDE.md のチェックリスト）】
#   評価件数       500件
#   基準線         衝突確率 10.8%（鍵35，m=1/m=2 とも同じ。偏りによる嵩上げなし）
#   基準線を先に   m=1 を先に回す。これは動的参照が消えた状態＝対照であり，
#                  「この設定で学習が成立すること」を示す役割を持つ
#   床の可能性     m=2 が離陸しなくても「鍵4マスでも動的参照は学習されない」と言える
#   鍵の本数       鍵35 のみ。8b（鍵0）と基準線を揃えるため1本に絞る。
#                  結果が出たら段階2 で別の健全な鍵（seed 30 [1,2,7,4]）を足す
#   1条件1回       段階1 は seed42 のみ。段階2 で別シードを足す
#   予算の混入     実験8a・8b と同じ 20エポック・定数学習率
#   過去との比較   8b 段階1（k=10, 鍵0）と同一条件。違うのは鍵サイズだけ
#
# 【この設計の弱点（解析で必ず扱うこと）】
#   k=4 では関連する組み合わせが少ないため，学習1000件が評価を覆ってしまう。
#     m=1 … 1,024 通り，評価500件のうち**約62%が学習で既出**
#     m=2 … 4,096 通り，評価500件のうち**約22%が既出**
#   ここでの「既出」は14個の入力そのものではなく（4^14 なのでまず重複しない），
#   答えを決める位置の組（m=1 なら X0,X10..X13）が既出という意味である。
#   したがって **m=1 が高得点でも丸暗記の可能性を排除できない**。
#   評価後に既出／未出に分けて正解率を出し，両方を記録すること。
#   未出でも m=1 が高く m=2 が床なら，主張は保たれる。
#
# 【読み方】主データは検証損失。離陸＝0.15 を下回った最初のエポック。
#   学習損失だけ下がって検証損失が上がる場合（実験8a A2 の丸暗記）は離陸としない。
#
# 【どう転んでも報告できるか】
#   m=1 離陸・m=2 床  → 容量では説明できない。壁は構造にある（狙いどおり）
#   m=1 も m=2 も床    → 学習設定の側を疑う。次は規模ではなく手法を変える
#   m=1・m=2 とも離陸  → 壁は容量だった。8b の結論を鍵サイズの効果として測り直す
#
# 所要: 1本 約7.5時間 × 2本 ≒ 15時間
# =============================================================================
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/_common.sh"

HCP_TOTAL=2
hcp_init "実験9 段階1: 最小課題（鍵4マス）"
HCP_EPOCHS=20
HCP_LR_SCHEDULER=constant

hcp_run --algorithm narrowptr_k4_m1 --key_seed 35 --data_seed 0 --seed 42
hcp_run --algorithm narrowptr_k4_m2 --key_seed 35 --data_seed 0 --seed 42

hcp_finish
