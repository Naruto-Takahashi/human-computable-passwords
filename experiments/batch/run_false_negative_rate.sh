#!/usr/bin/env bash
# =============================================================================
# 実験12 段階1: 偽陰性の再現率 — 素朴な手順の誤判定がどれだけ起きるか
#
# 【なぜ】本研究の第一貢献は「正解率が偶然水準付近でも学習不能とは言えない」
#   である。しかし現時点で実例は1件しかなく（table_add3_k10 鍵6，
#   10.2% → 100.0%），「たまたまそういう条件があった」と言われうる。
#   **「起きうる」を「どれだけ起きるか」に変える**のが本実験の目的である。
#
# 【母数】素朴な手順（5エポック・線形減衰・評価500件）で正解率40%未満と
#   判定された条件は **31件**ある（10アルゴリズムにまたがる）。
#   測り直し済みは2件のみで，うち1件が反転した。
#
# 【なぜ層別するか】1つの関数で鍵を6本振って全部反転しても
#   「簡単な関数を選んだ」と言われる。族をまたいで2本ずつ測れば，
#   族ごとの反転率が出せ，**どこで手順が失敗するか**まで言える。
#
#     静的3項        table_add3_k10   鍵1(10.6%) 鍵8(10.6%)
#     実質静的 m=1   narrowptr_k10_m1 鍵1( 9.8%) 鍵2(13.4%)
#     動的     m=2   narrowptr_k10_m2 鍵1( 9.6%) 鍵2(17.4%)
#
#   6件とも衝突確率（10.0〜10.5%）と区別できない位置にいる。
#   素朴な手順ならすべて「安全」と判定される。
#
# 【片側検定として設計する（1条件1runの正当化）】
#   反転した     → 決定的。モデルが実際に学習したので誤判定が確定する
#   反転しない   → 不確定。不運な run かもしれない（実験7）
#   したがって得られるのは**偽陰性率の下限**である。「31件中，少なくとも
#   N件が誤判定だった」と書ける。下限で足りるので2runずつ回す必要はない。
#
# 【信用のための錨（追加費用ゼロ）】
#   func_22_k10 は20エポックでも反転しなかった（11.4% / 23.6%，2シード）。
#   **予算を増やせば何でも100%になるわけではない**ことの証拠であり，
#   「学習するまで回しただけ」という批判への備えになる。測定済み。
#
# 【順序】族を交互に並べる。途中で止めても3本で3族を覆えるようにするため。
#
# 【見直し（CLAUDE.md のチェックリスト）】
#   評価件数       500件
#   基準線         鍵ごとの衝突確率（10.0 / 10.1 / 10.0 / 10.5 / 10.0 / 10.5%）
#   基準線を先に   素朴な手順での測定が基準線そのもので，すでに存在する
#   床の可能性     0件反転でも「鍵6は例外だった」と報告できる
#   鍵の本数       族ごとに2本
#   1条件1回       片側検定として正当化（上記）。下限を出すのが目的
#   予算の混入     20エポック・定数学習率（実験8a・8b・9と同一）。
#                  予算とスケジュールのどちらが効いたかの分離は実験11 の役目で，
#                  本実験の前提ではない（誤判定を示すには手順が直ればよい）
#   過去との比較   鍵・データ・学習件数・評価件数すべて同一。
#                  変えるのは予算と学習率スケジュールだけ
#   既出／未出     m=1 系は既出63%，m=2 系は0%。反転した条件は必ず分けて集計する
#                  （make seen-unseen RUN=<評価の run>）
#
# 【読み方】反転の判定は**収束（最小検証損失 < 0.02）**とする。横断集計で，
#   収束の有無が「正解率90%以上か否か」と60件すべてで一致しているため
#   （make corpus）。正解率も併記する。
#
# 【どう転んでも報告できるか】
#   反転が出る   → 「31件中少なくともN件が誤判定」。論文の主結果になる
#   1件も出ない  → 鍵6 が例外だったことになり，第一貢献は実例1件のまま。
#                  その場合は主張を弱め，測定規則の提示に重心を移す
#   族で差が出る → 「静的では誤判定するが動的では判定が正しい」と言える。
#                  手順の失敗する範囲が特定できるので，むしろ良い結果
#
# 所要: 1本 約7.5時間 × 6本 ≒ 45時間
# =============================================================================
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/_common.sh"

HCP_TOTAL=6
hcp_init "実験12 段階1: 偽陰性の再現率"
HCP_EPOCHS=20
HCP_LR_SCHEDULER=constant

hcp_run --algorithm table_add3_k10   --key_seed 1 --data_seed 0 --seed 42
hcp_run --algorithm narrowptr_k10_m1 --key_seed 1 --data_seed 0 --seed 42
hcp_run --algorithm narrowptr_k10_m2 --key_seed 1 --data_seed 0 --seed 42
hcp_run --algorithm table_add3_k10   --key_seed 8 --data_seed 0 --seed 42
hcp_run --algorithm narrowptr_k10_m1 --key_seed 2 --data_seed 0 --seed 42
hcp_run --algorithm narrowptr_k10_m2 --key_seed 2 --data_seed 0 --seed 42

hcp_finish
