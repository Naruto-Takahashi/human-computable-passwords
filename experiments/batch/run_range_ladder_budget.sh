#!/usr/bin/env bash
# =============================================================================
# 実験8b 段階1: 参照範囲ラダーを学習予算を外して測り直す（m=1, 2）
#
# 【なぜ】実験8a で，同じ鍵0・同じ設定（20エポック・定数学習率）のもとで
#   静的参照は離陸し（table_add3_k10 鍵6: 10.2% → 100%），
#   動的参照 m=10（func_22_k10）は2本とも汎化として離陸しなかった
#   （11.4% 不動／23.6% 丸暗記）。
# 両端が「離陸する」と「離陸しない」に分かれたので，その間のどこで学習できなく
# なるかを探す。
#
#   narrowptr_k10_m{m}:  j = (X[10] + X[11]) mod m,  Z = (X[j] + X[12] + X[13]) mod 10
#   m は「ポインタの行き先の数」。m=1 は静的，m=10 は func_22_k10 と同一。
#
# 【一度に全部回さない理由】m ∈ {1,2,3,5} × 2シードを一括で回すと約60時間かかり，
# 途中で方針を変えられない（走行中のスクリプトは編集できない）。
# m=2 の結果で次に回すべき m が決まるので，段階に分ける。
#
#   段階1（本スクリプト，約15時間）: m=1, m=2 × seed42
#     m=1 … 端点の確認。これが離陸しなければラダーは成立しない
#           （m=1 のルール文は「mod 1」を含み，鍵0・20エポックでは未検証）
#     m=2 … 最も弱い動的参照。ここが分かれ目になる
#   段階2: m=2 が離陸したら m=5 → m=3（二分探索），しなければ m=2 の別シードと m=3
#   段階3: 境界の前後に別シードを足す
#
# 【見直し（CLAUDE.md のチェックリスト）】
#   評価件数       500件
#   基準線         衝突確率 10.3%（鍵0 で m=1,2,3,5,10 すべて同じ。偏りによる嵩上げなし）
#   基準線を先に   m=1 を先に回す
#   床の可能性     m≥2 がすべて離陸しなくても「行き先が2通りでも学習されない」と言える
#   鍵の本数       鍵0 のみ。m=10 の比較対象（実験8a）が鍵0 にしかないため。
#                  境界が見つかったら別の鍵で確かめる（段階3 以降）
#   1条件1回       段階1 は seed42 のみ。境界の前後は段階3 で別シードを足す
#   予算の混入     実験8a と同じ 20エポック・定数学習率。20エポックで打ち切りとみなす
#   過去との比較   m=10 は実験8a の2本（同条件）をそのまま使う
#
# 【読み方】主データは検証損失。離陸＝0.15 を下回った最初のエポック。
#   実験8a の A2 のように学習損失だけ下がって検証損失が上がる（丸暗記）場合は
#   離陸とみなさない。保存されるのは最終エポックの重みなので，正解率は
#   丸暗記に入った後の値になりうる。最小の検証損失とそのエポックも併記する。
#
# 所要: 1本 約7.5時間（実験8a 実測 415〜454分）× 2本 ≒ 15時間
# =============================================================================
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/_common.sh"

HCP_TOTAL=2
hcp_init "実験8b 段階1: 参照範囲ラダー（予算を外す）"
HCP_EPOCHS=20
HCP_LR_SCHEDULER=constant

hcp_run --algorithm narrowptr_k10_m1 --key_seed 0 --data_seed 0 --seed 42
hcp_run --algorithm narrowptr_k10_m2 --key_seed 0 --data_seed 0 --seed 42

hcp_finish
