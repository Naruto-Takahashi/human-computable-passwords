#!/usr/bin/env bash
# =============================================================================
# 実験9 段階3: 再現と，加算項数の天井の特定
#
# 【なぜ】段階1・2 で経路Bの中心的主張が覆った（experiment_index.md 実験9）。
#
#     narrowptr_k4_m2（動的・3項）  100.0%  未出 399/399，ep12 で離陸
#     table_add6_k4  （静的・6項）   10.6%  20エポック通して検証損失が平坦
#
#   だが各条件1回のみである。ここで再現を取る。
#
# 【失敗のほうを先に再現する】2つの結果は偶然への脆さが違う。
#   - m=2 の 100%（未出399件すべて正解）は**まぐれでは起こらない**。
#     「動的参照は構造的な壁＝決して学習できない」という主張に対しては，
#     1回の成功で反証として足りる。
#   - table_add6 の平坦は1回では何も言えない。実験7 で「同一条件でも離陸する
#     かしないかで 10.2% / 100% に割れる」ことが分かっており，まさにこの形の
#     失敗が run のばらつきだった前例がある。
#   したがって table_add6_k4 の別シードを最優先で回す。
#
# 【順序と意図】途中で止めても価値の高いものから終わるように並べる。
#   1. table_add6_k4  seed1  … 失敗の再現（最優先）
#   2. narrowptr_k4_m2 seed1 … 成功がシードに依らないかの確認
#   3. table_add5_k4  seed42 … 項数の天井を刻む最初の一段（5項は学習できるか）
#
# 【見直し（CLAUDE.md のチェックリスト）】
#   評価件数       500件
#   基準線         衝突確率 10.0%（table_add6）／10.8%（narrowptr m2）／10.1%（table_add5）
#   基準線を先に   段階1・2 が同一条件の基準線になっている
#   床の可能性     table_add6 が2回とも平坦なら「6項は学習されない」と言える。
#                  1回でも離陸したら段階1・2 の解釈は撤回する
#   鍵の本数       鍵35 のみ。段階1・2 と揃えるため。鍵の一般性は段階4 で
#                  別の健全な鍵（seed 30 [1,2,7,4]）を足して確かめる
#   1条件1回       本段階がその解消。2条件目までで各2runになる
#   予算の混入     実験8a・8b・9 と同じ 20エポック・定数学習率
#   過去との比較   段階1・2 と同じ鍵・予算・評価件数。違うのは学習シードだけ
#
# 【主データは検証損失の形】正解率より，20エポック分の曲線を見る。
#   単調降下（narrowptr m2: 0.1872→0.0000）か，完全な平坦（table_add6: 0.19 固定）か。
#   「離陸が遅れただけ」と「最適化が始まっていない」は曲線で区別できる。
#
# 【どう転んでも報告できるか】
#   table_add6 が2回とも平坦 → 項数が壁。段階4 で天井（4か5か6か）を確定させる
#   table_add6 が離陸        → 段階2 は run のばらつきだった。壁の候補から項数が外れ，
#                              残るのは空間の大きさだけになる。その線で測り直す
#   m=2 がシードで割れる     → 成功する run が存在する事実は変わらないので
#                              「動的参照は壁ではない」は維持。ただし難易度の記述は要調整
#
# 所要: 1本 約7.5時間 × 3本 ≒ 22.5時間
# =============================================================================
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/_common.sh"

HCP_TOTAL=3
hcp_init "実験9 段階3: 再現と項数の天井"
HCP_EPOCHS=20
HCP_LR_SCHEDULER=constant

hcp_run --algorithm table_add6_k4   --key_seed 35 --data_seed 0 --seed 1
hcp_run --algorithm narrowptr_k4_m2 --key_seed 35 --data_seed 0 --seed 1
hcp_run --algorithm table_add5_k4   --key_seed 35 --data_seed 0 --seed 42

hcp_finish
