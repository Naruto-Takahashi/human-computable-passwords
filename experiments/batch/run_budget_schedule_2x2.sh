#!/usr/bin/env bash
# =============================================================================
# 実験11: 予算とスケジュールを分離する（第一貢献の根幹を固める）
#
# 【なぜ】実験8a で「5エポックという予算が測定器だった」と結論したが，
#   そのとき**エポック数と学習率スケジュールを同時に変えていた**。
#   指導教員へのレビュー（09/13 報告に対して）で指摘された点である。
#
#   `table_add3_k10` 鍵6・ds0 の測定は対角線しかない。
#
#              線形減衰        定数
#     5ep      10.2%  ✓        **未測定**
#     20ep     **未測定**       100.0% ✓
#
#   したがって現時点で言えるのは「予算と学習率スケジュールの組み合わせが
#   測定器だった」までである。査読者は必ず「どちらだったのか」を訊く。
#   第一貢献（偶然水準は安全の根拠にならない）の根幹に関わるため，先に塞ぐ。
#
# 【決定的なのは 5ep + 定数】ステップ数を5エポックのまま，学習率だけ落とさない。
#   実験7 によれば鍵6/ds0 は5エポック以内に離陸せず，20エポック・定数では
#   **3エポック目**で離陸している。時間としては5エポックでも足りていたはずで，
#   線形減衰では3エポック目の学習率が既にピークの4割まで落ちていたことになる。
#
#     5ep + 定数が離陸する   → 原因は**スケジュール**。ステップ数ではない
#     5ep + 定数が離陸しない → ステップ数も効いている。両者の合わせ技
#
# 【20ep + 線形を入れる理由】正方形を閉じるため。20エポックの線形減衰なら
#   3エポック目の学習率はピークの85%程度で，5エポック線形より遥かに高い。
#   ここで離陸すれば上の読みと整合する。
#
# 【主データは離陸エポック】正解率ではない。実験7 で同じ鍵6が data_seed 次第で
#   10.2% / 100.0% / 96.2% に割れており，正解率は「離陸が予算内に入ったか」の
#   二値を粗く写したものでしかない。検証損失が 0.15 を下回った最初のエポックを見る。
#
# 【見直し（CLAUDE.md のチェックリスト）】
#   評価件数       500件
#   基準線         衝突確率 10.3%（鍵6）
#   基準線を先に   対角の2セルは測定済み（実験7・8a）
#   床の可能性     どのセルでも離陸エポックが得られるので床でも情報が残る
#   鍵の本数       鍵6・ds0 のみ。**この条件に限った主張になる**。
#                  実験7 のとおり ds1・ds2 は5エポック線形でも離陸しており，
#                  本実験は「離陸しなかった条件で何が効いたか」を問うている
#   1条件1回       決定的な 5ep+定数 は2シードで回す
#   予算の混入     本実験はまさにそれを分離するもの
#   過去との比較   対角2セルは同じ鍵・同じ ds・同じ評価件数
#
# 【どう転んでも報告できるか】
#   5ep+定数が離陸   → 「学習率スケジュールが測定器だった」と正確に言える
#   離陸しない       → 「予算とスケジュールの両方」。表現をそう改める
#   2シードで割れる  → その割れ自体が実験7 の再確認になる
#
# 所要: 5ep 2本 約2.5時間 ＋ 20ep 1本 約7.5時間 ≒ 12.5時間
# =============================================================================
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/_common.sh"

HCP_TOTAL=3
hcp_init "実験11: 予算とスケジュールの分離"

# 決定的なセル（ステップ数は5エポックのまま，学習率を落とさない）
hcp_run --algorithm table_add3_k10 --key_seed 6 --data_seed 0 --seed 42 \
        --epochs 5 --lr_scheduler constant
hcp_run --algorithm table_add3_k10 --key_seed 6 --data_seed 0 --seed 1 \
        --epochs 5 --lr_scheduler constant

# 正方形を閉じるセル
hcp_run --algorithm table_add3_k10 --key_seed 6 --data_seed 0 --seed 42 \
        --epochs 20 --lr_scheduler linear

hcp_finish
