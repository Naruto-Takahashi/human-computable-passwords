#!/usr/bin/env bash
# =============================================================================
# 実験C6: 数字を付け替えて I_1 だけを動かしても離陸は変わるか（2026-10-30 設計）
# =============================================================================
# 鍵の数字の付け替え σ' = π∘σ は，どの位置どうしが同じ数字かとヒストグラムの形を
# 変えず，I_1 だけを動かす。同じ鍵から I_1 の低い版（≤0.002）と高い版（0.010〜0.020）を
# 作り（期待基準線の差が最小の組），離陸が I_1 に従って入れ替わるかを対で見る。
# 付け替えは乱数を消費しないので，2つの版のチャレンジ（データ）は完全に同じになる。
#
# 鍵と付け替え: experiments/select_C6_keys.py が選んだ15本（results/path_c/C6_keys.json）
# 構成・予算は C2 と同一（d_model 32・2層・cls・lr 1e-3・50,000件 × 100エポック）。
# 関数: f_{1,3}（func_13_k26）。初期値: 700, 701（2つの版で共通）。
# run 数: 15鍵 × 2版 × 2初期値 = 60。1 run 約17分（C2.1 の実測，8並列・2スレッド）。
# 1プロセス = 1鍵 × 1版 × 初期値2通りの30プロセスで，全体で約2.3時間。
# 低い版と高い版を交互に並べる（途中で止めても対がそろう）。
#
# 使い方:
#   HCP_DRY_RUN=1 bash experiments/batch/run_C6.sh
#   nohup bash experiments/batch/run_C6.sh > results/logs/C6.out 2>&1 & disown
#
# 集計: jsonl を直接読む。版は digit_perm で区別できる（C6_keys.json と突き合わせる）。
# =============================================================================
set -uo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/../.."
JOBS=${HCP_JOBS:-8}
THREADS=${HCP_THREADS:-2}
PY=.venv/bin/python

# 鍵seed:付け替え（select_C6_keys.py の出力）
LOW="60000000:0245368719 60000001:8401762935 60000002:9570214368 60000007:3067594281 \
60000023:2364517980 60000025:7431086925 60000027:6892134507 60000028:2673089514 \
60000029:6947250381 60000032:9081452736 60000036:2507618394 60000041:2150964783 \
60000045:1674230859 60000048:0861973425 60000064:6320854917"
HIGH="60000000:6013749825 60000001:8014365972 60000002:1947802563 60000007:6031258794 \
60000023:5643781092 60000025:4230567189 60000027:5618029473 60000028:1632784905 \
60000029:1693254078 60000032:8761032459 60000036:3071269584 60000041:7384296051 \
60000045:4302817659 60000048:1896523470 60000064:4716598302"

COMMON="--algorithm func_13_k26 --datasize 50000 --epochs 100 --readout cls --d_model 32 \
--num_layers 2 --learning_rate 0.001 --warmup_epochs 0 --init_seed_base 700 --runs 2 --experiment C6"

plan() {
  set -- $HIGH
  for lo in $LOW; do
    hi=$1; shift
    echo "--key_seeds ${lo%%:*} --digit_perm ${lo##*:} $COMMON"
    echo "--key_seeds ${hi%%:*} --digit_perm ${hi##*:} $COMMON"
  done
}

N=$(plan | wc -l)
echo "=== [$(date '+%m/%d %H:%M:%S')] 実験C6: ${N} プロセス / $((N * 2)) run を ${JOBS} 並列 ==="
echo "    f13（N=26）の鍵15本 × 低い版・高い版 × 初期値2"
plan | nl
if [ "${HCP_DRY_RUN:-}" = "1" ]; then
  echo "HCP_DRY_RUN=1 のため学習はしない"
  exit 0
fi
export OMP_NUM_THREADS=$THREADS TF_NUM_INTRAOP_THREADS=$THREADS TF_NUM_INTEROP_THREADS=1
plan | xargs -P "$JOBS" -I{} sh -c \
  "$PY experiments/train_pathC.py {} 2>/dev/null | grep -E 'run[0-9]|±'"
echo "=== [$(date '+%m/%d %H:%M:%S')] 完了 ==="
echo "集計: results/path_c/C6/*.jsonl を鍵ごとの対にまとめ（どちらかの初期値で離陸＝離陸），不一致の対を片側符号検定で見る"
